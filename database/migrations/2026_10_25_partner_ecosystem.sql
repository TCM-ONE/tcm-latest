-- TCM One institutional partner ecosystem (additive migration).
-- Apply once against the existing MySQL database. No current data is removed.

ALTER TABLE users
    MODIFY role ENUM('admin','student','partner_owner','partner_staff') NOT NULL DEFAULT 'student';

CREATE TABLE IF NOT EXISTS partners (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    partner_code VARCHAR(24) NOT NULL,
    legal_name VARCHAR(255) NOT NULL,
    display_name VARCHAR(180) NOT NULL,
    slug VARCHAR(200) NOT NULL,
    contact_person VARCHAR(150) DEFAULT NULL,
    email VARCHAR(190) DEFAULT NULL,
    phone VARCHAR(30) DEFAULT NULL,
    institution_type VARCHAR(100) DEFAULT NULL,
    partnership_type ENUM('academic','referral','custom') NOT NULL DEFAULT 'academic',
    status ENUM('new_lead','agreement_pending','onboarding','active','paused','expired','terminated') NOT NULL DEFAULT 'new_lead',
    city VARCHAR(100) DEFAULT NULL,
    state VARCHAR(100) DEFAULT NULL,
    postal_code VARCHAR(20) DEFAULT NULL,
    address TEXT DEFAULT NULL,
    website VARCHAR(255) DEFAULT NULL,
    logo_path VARCHAR(255) DEFAULT NULL,
    cover_path VARCHAR(255) DEFAULT NULL,
    description TEXT DEFAULT NULL,
    public_email VARCHAR(190) DEFAULT NULL,
    public_phone VARCHAR(30) DEFAULT NULL,
    whatsapp VARCHAR(30) DEFAULT NULL,
    map_url VARCHAR(500) DEFAULT NULL,
    public_status ENUM('draft','pending_review','published','rejected') NOT NULL DEFAULT 'draft',
    profile_completeness TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uniq_partners_code (partner_code),
    UNIQUE KEY uniq_partners_slug (slug),
    KEY idx_partners_status (status, public_status),
    KEY idx_partners_city (city),
    CONSTRAINT fk_partners_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS partner_memberships (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    partner_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    title VARCHAR(100) DEFAULT NULL,
    can_view_finance TINYINT(1) NOT NULL DEFAULT 0,
    status ENUM('invited','active','suspended') NOT NULL DEFAULT 'invited',
    invited_at DATETIME DEFAULT NULL,
    accepted_at DATETIME DEFAULT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uniq_partner_member (partner_id,user_id),
    KEY idx_member_user (user_id,status),
    CONSTRAINT fk_membership_partner FOREIGN KEY (partner_id) REFERENCES partners(id) ON DELETE CASCADE,
    CONSTRAINT fk_membership_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

